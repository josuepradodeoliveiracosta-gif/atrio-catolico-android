"""Pure in-memory Guardian V2 QA broker fixture; NOT an IAM security boundary.

No HTTP server, tokens, Google Cloud clients, Firestore emulator, or production I/O.
Principal identity is injected by the TEST HARNESS, never parsed from requests.
State transitions are serialized only in this single Python process and must not
be mistaken for Firestore transactions, cross-instance quotas, or deployed CAS.
"""
from __future__ import annotations

from copy import deepcopy
from datetime import datetime, timedelta, timezone
import hashlib
from threading import RLock

from scripts.guardian_v2_qa_mediator_contract import (
    QA_FIXTURE_PROJECT, simulate_qa_intent,
)

TRIAGE_PRINCIPAL = "qa-fixture-triage"
ACTIVATION_PRINCIPAL = "qa-fixture-activation"
TEST_REVISION = "2026-11-14T10:00:00Z"
_POLICY_START = datetime(2026, 11, 14, 9, 0, 0, tzinfo=timezone.utc)
_ROLES = {TRIAGE_PRINCIPAL: "triage", ACTIVATION_PRINCIPAL: "activation"}


def fixture_case_id(path: str) -> str:
    """Match the initial guardian-v2 case-ID shape, with no remote reads."""
    return "guard_" + hashlib.sha256(("atrio-guardian-v2:" + path).encode()).hexdigest()[:32]


def _decision(allow: bool, operation: str = "") -> dict:
    result = {"decision": "SIMULATED_ALLOW" if allow else "SIMULATED_DENY",
              "production_authorized": False}
    if allow:
        result["operation"] = operation
    return result


class OfflineBrokerFixture:
    """Synthetic, locked transactional state for adversarial QA exercises only."""

    def __init__(self, *, project=QA_FIXTURE_PROJECT, max_cases=2,
                 emergency_stop=False, allow_hold=False):
        if (project != QA_FIXTURE_PROJECT or
                type(max_cases) is not int or not 1 <= max_cases <= 10 or
                type(emergency_stop) is not bool or type(allow_hold) is not bool):
            raise ValueError("qa_fixture_only")
        self._project = project
        self._lock = RLock()
        self._version = 0
        self._max_cases = max_cases
        self._policy = {
            "update_time": "2026-11-14T09:00:00Z",
            "enabled": False,
            "autonomous_write_enabled": False,
            "emergency_stop": emergency_stop,
            "allow_hold": allow_hold,
        }
        self._sources = {
            "posts/synthetic_post": {"owner_uid": "synthetic_actor",
                                     "update_time": TEST_REVISION},
            "posts/seed/replies/answer": {"owner_uid": "synthetic_actor",
                                          "update_time": TEST_REVISION},
            "posts/another": {"owner_uid": "synthetic_actor",
                               "update_time": TEST_REVISION},
        }
        self._cases = {}
        self._audits = {}
        self._notices = {}
        self._budget = 0

    def snapshot(self) -> dict:
        """Return a defensive copy, never the writable backing state."""
        with self._lock:
            return deepcopy({
                "project": self._project, "policy": self._policy,
                "cases": self._cases, "audits": self._audits,
                "notices": self._notices, "budget": self._budget,
                "max_cases": self._max_cases,
            })

    def handle(self, *, trusted_principal: str, request: object,
               manually_approved: bool = False) -> dict:
        """Apply a QA-only transition under a trusted synthetic principal.

        There is intentionally no token verifier and no generic write endpoint.
        """
        role = _ROLES.get(trusted_principal) if type(trusted_principal) is str else None
        if not role:
            return _decision(False)
        with self._lock:
            result = simulate_qa_intent(
                project=self._project, trusted_role=role, request=request,
                manually_approved=manually_approved, policy_snapshot=self._policy,
            )
            if result["decision"] != "SIMULATED_ALLOW":
                return _decision(False)

            operation = request["operation"]
            if operation == "read_policy" and role == "triage":
                # The only read available to the synthetic triage principal.
                return {**_decision(True, operation), "policy": deepcopy(self._policy)}

            if operation == "enable_nonpunitive" and role == "activation":
                if (self._policy["enabled"] or
                        self._policy["autonomous_write_enabled"]):
                    return _decision(False)
                # The client supplied only an expected revision. Two allowed
                # fields and the synthetic revision are generated by the broker.
                self._version += 1
                updated = dict(self._policy)
                updated["enabled"] = True
                updated["autonomous_write_enabled"] = True
                updated["update_time"] = (
                    _POLICY_START + timedelta(seconds=self._version)
                ).isoformat().replace("+00:00", "Z")
                self._policy = updated
                return {**_decision(True, operation),
                        "policy_update_mask": ["enabled", "autonomousWriteEnabled"]}

            if operation == "propose_case" and role == "triage":
                if (not self._policy["enabled"] or
                        not self._policy["autonomous_write_enabled"] or
                        self._policy["emergency_stop"] or self._policy["allow_hold"]):
                    return _decision(False)
                target, owner, case_id = (
                    request["target_path"], request["owner_uid"], request["case_id"]
                )
                source = self._sources.get(target)
                if (source is None or source["owner_uid"] != owner or
                        source["update_time"] != request["source_update_time"] or
                        fixture_case_id(target) != case_id or
                        case_id in self._cases or self._budget >= self._max_cases):
                    return _decision(False)
                # All synthetic effects are derived from trusted fixture state.
                # No arbitrary caller-supplied document name or raw Firestore
                # write object reaches this transition.
                self._cases[case_id] = {"target": target, "owner": owner,
                                        "status": request["status"]}
                self._audits[case_id] = {"event": request["status"], "actor": "guardian_v2"}
                self._notices[case_id] = {"owner": owner, "case_id": case_id}
                self._budget += 1
                return {**_decision(True, operation), "created": ["case", "audit", "notice"],
                        "budget_used": self._budget}

            return _decision(False)
